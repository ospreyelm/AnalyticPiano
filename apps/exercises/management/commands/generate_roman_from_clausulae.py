"""Generate Roman numeral identification exercises from Clausulae content.

These exercises are DISTINCT from Branch B clausulae (generate_clausulae_b1):

  Branch B clausulae  — playback mode, scale-degree circle labels, voice-leading pedagogy.
  roman_from_clausulae — identification mode, Roman numeral labels, standard curriculum.

The musical content (voices, grading slices) is generated by the same clausulae engine
that drives Branch B.  Only the analysis slices, mode, and metadata differ.

Roman numeral analysis for a simple authentic cadence (all major keys):
  ANT  offset 0.0  →  I
  PEN  offset 2.0  →  V
  ULT  offset 4.0  →  I

All three moments are identification targets (is_target=True).  The allowed-answer
pool is expanded to all seven diatonic triads so the student must actually identify
the chord rather than guess between two options.

⚠  VERIFICATION STANDARD (from docs/superpowers/specs/2026-05-26-roman-from-clausulae-lessons.md)
   Passing tests is not sufficient.  After generation:
   1. Open one exercise in the student app.
   2. Confirm the score is musically coherent (two measures, 2/2).
   3. Confirm three ? slots appear at the right positions.
   4. Confirm the student can answer and complete the exercise.
   Only after this smoke test should the generator be expanded to other units.

Usage:
    python manage.py generate_roman_from_clausulae \\
        --unit 9 --author admin@example.com --voices 3 --public --overwrite
"""
