# ── Constants ─────────────────────────────────────────────────────────────────

HL_KEY = {
    "C": "jC_", "G": "jG_", "F": "jF_", "D": "jD_", "Bb": "jBb",
    "A": "jA_", "Eb": "jEb", "E": "jE_", "Ab": "jAb",
}

TARGET_KEYS = ["C", "F", "G", "D", "Bb"]

# Voice → MIDI octave (matches generate_clausulae_b1)
_OCTAVE = {"S": 5, "A": 4, "T": 4, "B": 3}

# ANT=half, PEN=half, ULT=whole (same as _DUR_SIMPLE in generate_clausulae_b1)
_DUR_SIMPLE = [("h", 2.0), ("h", 2.0), ("w", 4.0)]

# Harmonic rhythm for a simple authentic cadence — I at ANT, V at PEN, I at ULT
_CADENCE_RN = [(0.0, "I"), (2.0, "V"), (4.0, "I")]

# Full diatonic triad pool for the identification UI.
# Expanded beyond {I, V} so students must actually identify each chord.
_RN_CHOICES_MAJOR = ["I", "ii", "iii", "IV", "V", "vi", "vii°"]

# Solfège labels per clausula type and variant (matches generate_clausulae_b1)
_SOLFEGE_LABELS: dict[str, list[str]] = {
    "Discant": ["Do–Ti–Do"],
    "Tenor":   ["Do–Re–Do", "Do–Re–Mi", "Mi–Re–Do", "Mi–Re–Mi"],
    "Alto":    ["Sol–Sol–Sol", "Sol–Fa–Mi", "Sol–La–Sol"],
    "Bass":    ["Do–Sol–Do"],
}

# Compact solfège abbreviations for exercise descriptions
_SOL_ABBR: dict[str, str] = {
    "Do–Ti–Do":    "D-Ti-D",
    "Do–Re–Do":    "D-Re-D",
    "Do–Re–Mi":    "D-Re-M",
    "Mi–Re–Do":    "M-Re-D",
    "Mi–Re–Mi":    "M-Re-M",
    "Sol–Sol–Sol": "S-S-S",
    "Sol–Fa–Mi":   "S-Fa-M",
    "Sol–La–Sol":  "S-La-S",
    "Do–Sol–Do":   "D-Sol-D",
}


# ── Shared generation utilities ───────────────────────────────────────────────
# These mirror the equivalents in generate_clausulae_b1.py.  They are
# intentionally kept local to avoid a cross-command import dependency.

def _solfege_label(clausula_name: str, var_idx: int) -> str:
    labels = _SOLFEGE_LABELS.get(clausula_name, [])
    return labels[var_idx] if var_idx < len(labels) else str(var_idx)


def _m21_note_to_pitch(n) -> Pitch:
    p = n.pitch
    alter_map = {
        None: 0, "sharp": 1, "flat": -1,
        "double-sharp": 2, "double-flat": -2,
    }
    alter = alter_map.get(p.accidental.name if p.accidental else None, 0)
    return Pitch(step=p.step, alter=alter, octave=p.octave, midi=p.midi)


def _realize_events(triple, key: str, voice_id: str) -> list[VoiceEvent]:
    """Realize a Z₇ triple into VoiceEvents using the standard ANT/PEN/ULT rhythm."""
    notes = key_realize(triple, key, octave=_OCTAVE[voice_id])
    return [
        VoiceEvent(
            kind="note",
            pitch=_m21_note_to_pitch(n),
            duration=ql,
            duration_type=dt,
            dots=0,
            is_target=True,
        )
        for n, (dt, ql) in zip(notes, _DUR_SIMPLE)
    ]


def _staff_dist(vids: set[str]) -> str:
    has_bass   = bool(vids & {"T", "B"})
    has_treble = bool(vids & {"S", "A"})
    if has_bass and has_treble:
        return "keyboard"
    return "bass" if has_bass else "treble"


def _grading_slices(
    voice_events_by_id: dict[str, list[VoiceEvent]],
    offsets: list[float],
) -> list[GradingSlice]:
    """One grading slice per onset: collect MIDI pitches from every voice at that index."""
    slices = []
    for offset_i, offset in enumerate(offsets):
        midi = []
        for events in voice_events_by_id.values():
            if offset_i < len(events) and events[offset_i].pitch:
                midi.append(events[offset_i].pitch.midi)
        slices.append(GradingSlice(offset=offset, target_midi_pitches=sorted(midi)))
    return slices


def _assign_slots(combo: tuple) -> dict[str, tuple]:
    """
    Map (name, var_idx, triple) tuples to SATB voice slots.
    For 3-voice: Discant=S, Tenor/Alto=A, Bass=B.
    For 4-voice: Discant=S, Alto=A, Tenor=T, Bass=B.
    """
    n = len(combo)
    if n <= 3:
        vid_map = {"Discant": "S", "Tenor": "A", "Alto": "A", "Bass": "B"}
    else:
        vid_map = {"Discant": "S", "Alto": "A", "Tenor": "T", "Bass": "B"}

    result: dict[str, tuple] = {}
    for name, idx, triple in combo:
        vid = vid_map[name]
        if vid in result:
            # Fallback: put a duplicate Tenor into A if A is free
            if vid == "T" and "A" not in result:
                vid = "A"
        result[vid] = (name, idx, triple)
    return result


def _combo_label(slots: dict[str, tuple]) -> str:
    """Stable, compact label identifying the voice combination — used in descriptions."""
    parts = []
    for vid in ["S", "A", "T", "B"]:
        if vid not in slots:
            continue
        name, var_idx, _ = slots[vid]
        sol = _solfege_label(name, var_idx)
        abbr = _SOL_ABBR.get(sol, sol)
        parts.append(f"{name[0]}:{abbr}")
    return " ".join(parts)


# ── Unit-aware payload builder ────────────────────────────────────────────────

_CANDIDATE_UNITS = [9, 10, 11, 12, 14]  # unit 13 (ROO) + double cadences deferred
_UNIT_TABLE = compute_unit_allowed_answers()


def structural_targets(family: str) -> list[tuple[float, float]]:
    """Return (target_offset, analysis_source_offset) pairs by cadence family.

    For compound cadences the penult target is placed at 2.0 (dominant-with-
    suspension onset) but the RN is derived from the resolved sonority at 3.0
    (the suspension has resolved). Simple and all other families analyze each
    position directly.
    """
    if family == "compound":
        # τ=1 voice: rest@0, ANT@1, dominant-with-suspension onset@2, resolved
        # PEN@3, ULT@4. Show ? at 2.0 but derive the answer from offset 3.0.
        return [(0.0, 0.0), (2.0, 3.0), (4.0, 4.0)]
    return [(0.0, 0.0), (2.0, 2.0), (4.0, 4.0)]


def build_binned_payload(
    voices: Voices,
    *,
    key: str,
    family: str,
    n_voices: int,
    fingerprint: str,
    upper_figures=None,
):
    """Return (payload, unit, derived_rns) or None if no unit covers the RNs.

    voices       – SATB Voices dataclass
    key          – tonal centre ('C', 'G', etc.)
    family       – clausula family ('simple', 'compound', 'double')
    n_voices     – number of active voices (2, 3, or 4)
    fingerprint  – stable string identifying the voice combination (for hashing)
    upper_figures – optional set of figured-bass integers (compound 4-voice titles)
    """
    targets = structural_targets(family)
    verticals = derive_cadence(voices, key=key, targets=targets)
    rn_list = [v["rn"] for v in verticals]
    unit = bin_unit(set(rn_list), _UNIT_TABLE, _CANDIDATE_UNITS)
    if unit is None:
        return None

    analysis = [
        AnalysisSlice(
            offset=v["offset"],
            content=AnalysisLayer(roman_numeral=v["rn"], raw_roman_numeral=v["rn"]),
            unit_tags=[unit],
            is_target=True,
        )
        for v in verticals
    ]
    grading = [
        GradingSlice(offset=v["offset"], target_midi_pitches=v["midi"])
        for v in verticals
    ]
    vids = {vid for vid in ("S", "A", "T", "B") if getattr(voices, vid)}

    umto = UMTO(
        metadata=Metadata(
            exercise_id="TEMP",
            source=student_title(family, n_voices, key=key, upper_figures=upper_figures),
            key=HL_KEY.get(key, "jC_"),
            meter="2/2",
            clef=_staff_dist(vids),
            complexity_score=unit,
            mode=InteractionMode.IDENTIFICATION,
            input_mode="dropdown",
            unit=unit,
        ),
        voices=voices,
        analysis=analysis,
        grading=grading,
    )

    payload = umto.to_frontend_payload(unit=unit, analysis_type="roman")

    # Override / extend fields that to_frontend_payload sets from metadata defaults.
    payload["analysisType"] = "roman"
    payload["identMode"] = "practice"
    payload["allowed_answers"] = list(_UNIT_TABLE[unit])
    payload["display"] = {
        "showNotation": True,
        "hideKeyLabel": False,
        "showScaleDegrees": False,
        "maxMeasures": 2,
    }
    payload["inputModeFixed"] = "dropdown"
    payload["description"] = short_description(
        family, n_voices, key=key, unit=unit, fingerprint=fingerprint
    )
    return payload, unit, rn_list


# ── Legacy payload builder (kept for _make_exercises; removed in Task 9) ──────

def _build_identification_payload(
    voice_events_by_id: dict[str, list[VoiceEvent]],
    key: str,
    description: str,
    unit: int,
) -> dict:
    """
    Build a umto_chorale identification payload with Roman numeral analysis.

    The three analysis slices (ANT/PEN/ULT) are all marked is_target=True so
    the student sees three ? slots and identifies I, V, I in sequence.
    """
    vids = set(voice_events_by_id.keys())
    offsets = [off for off, _ in _CADENCE_RN]

    analysis = [
        AnalysisSlice(
            offset=off,
            content=AnalysisLayer(roman_numeral=rn, raw_roman_numeral=rn),
            unit_tags=[unit],
            is_target=True,
        )
        for off, rn in _CADENCE_RN
    ]

    umto = UMTO(
        metadata=Metadata(
            exercise_id="TEMP",
            source=description,
            key=HL_KEY.get(key, "jC_"),
            meter="2/2",
            clef=_staff_dist(vids),
            complexity_score=unit,
            mode=InteractionMode.IDENTIFICATION,
            input_mode="dropdown",
            unit=unit,
        ),
        voices=Voices(
            S=voice_events_by_id.get("S", []),
            A=voice_events_by_id.get("A", []),
            T=voice_events_by_id.get("T", []),
            B=voice_events_by_id.get("B", []),
        ),
        analysis=analysis,
        grading=_grading_slices(voice_events_by_id, offsets),
    )

    payload = umto.to_frontend_payload(unit=unit, analysis_type="roman")

    # Override fields that to_frontend_payload sets from metadata defaults.
    payload["analysisType"]     = "roman"
    payload["identMode"]        = "practice"
    # Expose the full diatonic pool so the student faces real identification.
    payload["allowed_answers"]  = _RN_CHOICES_MAJOR
    # No Branch B display settings: no scale-degree circles, no voice colours.
    payload["display"] = {
        "showNotation":    True,
        "hideKeyLabel":    False,
        "showScaleDegrees": False,
        "maxMeasures":     2,
    }
    # Force dropdown UI so ? slots always render regardless of what the student
    # has stored in localStorage for their preferred input mode.
    payload["inputModeFixed"] = "dropdown"
    return payload


# ── Exercise and playlist persistence ─────────────────────────────────────────

def _save_exercise(
    *,
    author,
    description: str,
    payload: dict,
    skill_tags: list[str],
    complexity: int,
    is_public: bool,
    overwrite: bool,
) -> Exercise:
    ex = (
        Exercise.objects.filter(description=description, authored_by=author).first()
        if overwrite else None
    )
    if ex is None:
        ex = Exercise(
            description=description,
            data=payload,
            authored_by=author,
            is_public=is_public,
            skill_tags=list(skill_tags),
            complexity=complexity,
        )
        ex.save()
    else:
        ex.data       = payload
        ex.skill_tags = list(skill_tags)
        ex.complexity = complexity
        ex.is_public  = is_public
        ex.save(update_fields=["data", "skill_tags", "complexity", "is_public"])

    # Backfill the database-assigned id into the payload.
    ex.data["exerciseId"] = ex.id
    ex.data["score"]["umto"]["metadata"]["exercise_id"] = ex.id
    ex.save(update_fields=["data"])
    return ex


def _build_playlist(
    *,
    author,
    playlist_name: str,
    exercises: list[Exercise],
    skill_tags: list[str],
    is_public: bool,
) -> Playlist:
    playlist, _ = Playlist.objects.get_or_create(
        name=playlist_name,
        authored_by=author,
        defaults=dict(
            is_dynamic=False,
            is_adaptive=False,
            is_public=is_public,
            skill_tags=skill_tags,
        ),
    )
    playlist.skill_tags = skill_tags
    if is_public:
        playlist.is_public = True
    playlist.save()

    # Replace existing ordering with the freshly generated set.
    ExercisePlaylistOrdered.objects.filter(playlist=playlist).delete()
    for order, ex in enumerate(exercises, start=1):
        ExercisePlaylistOrdered.objects.create(
            playlist=playlist, exercise=ex, order=order
        )
    return playlist


# ── Per-voice-count generator ─────────────────────────────────────────────────

def _make_exercises(
    n_voices: int,
    unit: int,
    author,
    options: dict,
    stdout,
    style,
) -> list[Exercise]:
    """Generate all roman_from_clausulae exercises for a given voice count."""
    def _tonal_valid(combo) -> bool:
        """Filter combos to tonal-music constraints on ANT and ULT sonorities.

        Let ANT = set of scale degrees (Z₇) across all voices at the first position.
        Let ULT = set of scale degrees (Z₇) across all voices at the last position.

        KEEP iff:
          (1) 2 ∈ ANT  — first chord must contain the third (Mi)
          (2) NOT (4 ∈ ULT AND 2 ∉ ULT)  — last chord cannot be bare fifth/octave
                                             (Sol without Mi is not a complete tonic)
        Scale degrees: 0=Do, 2=Mi, 4=Sol (Z₇ diatonic integers).
        """
        ant = {triple[0] for _, __, triple in combo}
        ult = {triple[2] for _, __, triple in combo}
        has_third_at_start  = 2 in ant
        bad_end             = (4 in ult) and (2 not in ult)
        return has_third_at_start and not bad_end

    # Deduplicate by slot fingerprint: (slot_id, triple) pairs sorted by slot.
    # enumerate_simple returns both (Bass, Discant, Tenor) and (Bass, Tenor, Discant)
    # orderings; _assign_slots maps both to the same B/S/A slots, producing
    # identical exercises. Keep only the first occurrence of each fingerprint.
    def _slot_fingerprint(combo) -> frozenset:
        slots = _assign_slots(combo)
        return frozenset((vid, triple) for vid, (_, __, triple) in slots.items())

    seen: set = set()
    combos = []
    for c in enumerate_simple(n_voices=n_voices, require_bass=True):
        if not any(name == "Discant" for name, _, __ in c):
            continue
        if not _tonal_valid(c):
            continue
        fp = _slot_fingerprint(c)
        if fp in seen:
            continue
        seen.add(fp)
        combos.append(c)

    exs: list[Exercise] = []
    voice_str = f"{n_voices}-part"

    for key in TARGET_KEYS:
        for combo_idx, combo in enumerate(combos, 1):
            slots      = _assign_slots(combo)
            vmap: dict[str, list[VoiceEvent]] = {}
            for vid, (name, var_idx, triple) in slots.items():
                vmap[vid] = _realize_events(triple, key, vid)

            label = _combo_label(slots)
            # Human-readable prefix + compact label as idempotency key.
            # For 3-voice the label fits; for 4-voice use a shorter prefix
            # to stay within the varchar(60) description field.
            prefix = f"{voice_str} Authentic Cadence in {key}"
            candidate = f"{prefix} [{label}]"
            desc = candidate if len(candidate) <= 60 else f"{prefix} var{combo_idx}"

            payload = _build_identification_payload(vmap, key, desc, unit)

            skill_tags = [
                "exercise_type:roman_from_clausulae",
                "corpus:standard_exercises_from_clausulae",
                f"unit:{unit}",
                "mode:roman",
                f"voices:{n_voices}",
                "Cadence_Perfect_Authentic",
                "Diatonic_Triads",
            ]

            ex = _save_exercise(
                author=author,
                description=desc,
                payload=payload,
                skill_tags=skill_tags,
                complexity=unit,
                is_public=options["public"],
                overwrite=options["overwrite"],
            )
            exs.append(ex)
            stdout.write(f"  {desc}")

    return exs


# ── Management command ────────────────────────────────────────────────────────

class Command(BaseCommand):
    help = (
        "Generate Roman numeral identification exercises from Clausulae content. "
        "Standard curriculum — NOT Branch B. "
        "See docs/superpowers/specs/2026-05-26-roman-from-clausulae-lessons.md."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "--author", required=True,
            help="Email address of the exercise author.",
        )
        parser.add_argument(
            "--unit", type=int, default=9,
            help="Curriculum unit number for analysis slice unit_tags (default: 9).",
        )
        parser.add_argument(
            "--voices", choices=["3", "4", "all"], default="all",
            help="Voice count to generate: 3, 4, or all (default: all).",
        )
        parser.add_argument("--public",    action="store_true")
        parser.add_argument("--overwrite", action="store_true",
                            help="Replace existing exercises with matching descriptions.")

    def handle(self, *args, **options):
        if not _CLAUSULAE_AVAILABLE:
            raise CommandError(
                f"clausulae library not importable from {_CLAUSULAE_ROOT}.\n"
                f"Error: {_CLAUSULAE_IMPORT_ERROR}\n"
                "Run: pip install -e ../clausulae-project"
            )

        try:
            author = User.objects.get(email=options["author"])
        except User.DoesNotExist as exc:
            raise CommandError(f"Unknown author: {options['author']}") from exc

        unit       = options["unit"]
        voices_arg = options["voices"]
        voice_list = [3, 4] if voices_arg == "all" else [int(voices_arg)]

        all_exercises: list[Exercise] = []

        for n_voices in voice_list:
            self.stdout.write(self.style.MIGRATE_HEADING(
                f"roman_from_clausulae — {n_voices}-voice authentic cadences (Unit {unit})"
            ))
            exs = _make_exercises(
                n_voices, unit, author, options, self.stdout, self.style
            )
            all_exercises.extend(exs)
            self.stdout.write(
                self.style.SUCCESS(f"  → {len(exs)} exercises generated.")
            )

        # One playlist for the full run (or filtered voice count).
        playlist_suffix = "" if voices_arg == "all" else f" {voices_arg}-voice"
        playlist_name   = f"Unit {unit} — Authentic Cadences (Roman Numerals){playlist_suffix}"

        playlist = _build_playlist(
            author=author,
            playlist_name=playlist_name,
            exercises=all_exercises,
            skill_tags=[
                "exercise_type:roman_from_clausulae",
                f"unit:{unit}",
                "Cadence_Perfect_Authentic",
            ],
            is_public=options["public"],
        )

        self.stdout.write(self.style.SUCCESS(
            f"\nTotal: {len(all_exercises)} exercises → playlist '{playlist.name}'"
        ))
        self.stdout.write(
            "\n⚠  Remember to verify one exercise in the student app before bulk use.\n"
            "   Check: 2 measures display, 3 × ? slots, student can answer and complete."
        )
