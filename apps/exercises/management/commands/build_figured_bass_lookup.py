"""Generate lab/static/js/src/config/figured_bass_hints_data.js.

Emits an ESM data file with two lookups the student-facing figured-bass hint
layer reads at render time:

- ``_SHORTHANDS`` — a direct mirror of
  ``apps/exercises/harmonization/figures.py:_SHORTHANDS`` (abbreviated figure
  -> interval token list), used to expand abbreviated figures for
  identification-mode hints.
- ``_REQUIRED_NUMBERS_BY_FIGURE`` — ``{figure: {policy_key: [required generic
  interval numbers]}}``, computed by calling
  ``figure_realization.required_numbers()`` for every figure ``_SHORTHANDS``
  can produce, at the voice-count-policy shape the corpus actually uses
  (``{min: 3, max: 4}``). This is the same Python computation the grader
  trusts (``derive_required_notes``), so a hint can never contradict what the
  grader accepts for the same target.

The file is generated — never hand-edit it. Re-run after changes to
``figures.py`` or ``figure_realization.py``; the sync test
(``test_figured_bass_hints_data.py``) fails CI on drift. Python remains the
source of truth (AGENTS.md: no parallel Python/JavaScript allowlists).
"""
import json
import os

from django.core.management.base import BaseCommand

from apps.exercises.harmonization import figure_realization as fr
from apps.exercises.harmonization.figures import _SHORTHANDS, _parse_token, expand_figure_string

# Four levels up from apps/exercises/management/commands/ -> repo root
_OUT_PATH = os.path.abspath(os.path.join(
    os.path.dirname(__file__), "..", "..", "..", "..",
    "lab", "static", "js", "src", "config", "figured_bass_hints_data.js"
))

# Voice-count-policy shapes the corpus uses. Confirmed empirically (local dev
# + prod, 2026-07-03): every harmonization target uses {min:3,max:4}. Add a
# shape here only if a future exercise introduces a new one; regenerating then
# produces the new entries with no other changes.
_POLICIES = [{"min": 3, "max": 4}]


def _policy_key(policy: dict) -> str:
    return f"{int(policy.get('min', 3))}-{int(policy.get('max', 4))}"


def _present_and_altered(figure: str) -> tuple[set[int], frozenset[int]]:
    """Mirror derive_required_notes' token-based present/altered extraction.

    Which numbers are required is a pure function of the figure string and
    voice-count policy (never of key or bass) -- _parse_token yields the
    generic number and alteration per expanded token without any pitch
    context. 8 (octave doubling) is dropped: it is never a named requirement,
    only an optional doubling, and is rendered separately as [+8].
    """
    present: set[int] = set()
    altered: set[int] = set()
    for raw_token in expand_figure_string(figure):
        token = _parse_token(raw_token)
        if token.number == 8:
            continue
        present.add(token.number)
        if token.accidental or token.quality_alter:
            altered.add(token.number)
    return present, frozenset(altered)


def _required_for(figure: str, policy: dict) -> list[int]:
    present, altered = _present_and_altered(figure)
    prototype, _altered_from_norm = fr.normalize(figure)
    if prototype is None:
        # Fail-safe (matches derive_required_notes): all named tones required.
        return sorted(present)
    required = fr.required_numbers(prototype, policy, present=present, altered=altered)
    return sorted(required)


class Command(BaseCommand):
    help = "Generate the ESM figured_bass_hints_data.js lookup module."

    def handle(self, *args, **options):
        shorthands = {k: list(_SHORTHANDS[k]) for k in sorted(_SHORTHANDS)}
        required_by_figure: dict[str, dict[str, list[int]]] = {}
        for figure in sorted(_SHORTHANDS):
            required_by_figure[figure] = {
                _policy_key(policy): _required_for(figure, policy)
                for policy in _POLICIES
            }
        payload = {
            "_SHORTHANDS": shorthands,
            "_REQUIRED_NUMBERS_BY_FIGURE": required_by_figure,
        }
        body = json.dumps(payload, indent=2, ensure_ascii=False)
        module = (
            "// GENERATED by `manage.py build_figured_bass_lookup` — do not edit.\n"
            "// Source of truth: apps/exercises/harmonization/figures.py (_SHORTHANDS,\n"
            "// expand_figure_string) and apps/exercises/harmonization/figure_realization.py\n"
            "// (TABLE, normalize, required_numbers). Re-run after changes to either;\n"
            "// the sync test (test_figured_bass_hints_data.py) fails on drift.\n"
            f"export default {body};\n"
        )
        with open(_OUT_PATH, "w") as fh:
            fh.write(module)
        self.stdout.write(self.style.SUCCESS(f"Wrote {_OUT_PATH}"))